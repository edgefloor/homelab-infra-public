#!/usr/bin/env python3
"""Refresh a local CoreDNS blocklist or rebuild it from cached source domains."""

import argparse
import fcntl
import ipaddress
import json
import os
import re
import tempfile
from pathlib import Path
from urllib.parse import urlsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener


MAX_BYTES = 16 * 1024 * 1024
LABEL = re.compile(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?")


def domain(value):
    value = value.rstrip('.').lower().encode('idna').decode('ascii')
    if len(value) > 253 or '.' not in value or not all(LABEL.fullmatch(p) for p in value.split('.')):
        raise ValueError('invalid domain: ' + value)
    try:
        ipaddress.ip_address(value)
    except ValueError:
        return value
    raise ValueError('IP addresses are not domain rules')


def parse_hosts(text):
    domains = set()
    for line in text.splitlines():
        fields = line.split('#', 1)[0].split()
        if len(fields) < 2 or fields[0] not in {'0.0.0.0', '127.0.0.1', '::'}:
            continue
        for name in fields[1:]:
            try:
                domains.add(domain(name))
            except (ValueError, UnicodeError):
                continue
    return domains


class HTTPSOnlyRedirectHandler(HTTPRedirectHandler):
    def redirect_request(self, request, response, code, message, headers, new_url):
        # Reject each hop before urllib connects; checking only the final URL
        # permits an insecure intermediate hop to select the eventual source.
        if urlsplit(new_url).scheme != 'https':
            raise ValueError('blocklist redirected away from HTTPS')
        return super().redirect_request(request, response, code, message, headers, new_url)


def fetch(url):
    if urlsplit(url).scheme != 'https':
        raise ValueError('blocklist sources must use HTTPS')
    opener = build_opener(HTTPSOnlyRedirectHandler())
    with opener.open(Request(url, headers={'User-Agent': 'homelab-coredns-adblock/1'}), timeout=30) as response:
        if urlsplit(response.geturl()).scheme != 'https':
            raise ValueError('blocklist redirected away from HTTPS')
        data = response.read(MAX_BYTES + 1)
    if len(data) > MAX_BYTES:
        raise ValueError('blocklist download exceeded size limit')
    return data.decode('utf-8')


def atomic_write(path, content):
    if path.exists() and path.read_text() == content:
        return False
    fd, name = tempfile.mkstemp(prefix='.' + path.name, dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(fd, 'w') as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
            os.fchmod(handle.fileno(), 0o640)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)
    return True


def update(config, directory, refresh=False, download=fetch):
    exemptions = {domain(d) for key in ('allowlist', 'protected_domains') for d in config.get(key, [])}
    extra = {domain(d) for d in config.get('extra_domains', [])}
    minimum = int(config.get('minimum_domains', 10000))
    if minimum < 1:
        raise ValueError('minimum_domains must be positive')
    cache = directory / 'source-domains.txt'
    if refresh:
        sources = config['sources']
        if not sources or len(sources) > 10:
            raise ValueError('configure between one and ten hosts-format sources')
        domains = set()
        for url in sources:
            parsed = parse_hosts(download(url))
            if len(parsed) < minimum:
                raise ValueError('download has too few valid domains: ' + url)
            domains.update(parsed)
    else:
        domains = {domain(d) for d in cache.read_text().splitlines()}
    if len(domains) < minimum:
        raise ValueError('source cache has too few valid domains')
    blocked = set()
    for name in domains | extra:
        parts = name.split('.')
        if not any('.'.join(parts[i:]) in exemptions for i in range(len(parts))):
            blocked.add(name)
    content = '# Generated by coredns-adblock-update; edit /etc/coredns/adblock.json.\n'
    content += ''.join(f'0.0.0.0 {d}\n:: {d}\n' for d in sorted(blocked))
    # Validate all sources and rules before replacing either existing file.
    if refresh:
        atomic_write(cache, ''.join(d + '\n' for d in sorted(domains)))
    changed = atomic_write(directory / 'blocked.hosts', content)
    return {'changed': int(changed), 'domains': len(blocked), 'source_domains': len(domains),
            'test_domain': min(blocked) if blocked else ''}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=Path('/etc/coredns/adblock.json'))
    parser.add_argument('--directory', type=Path, default=Path('/var/lib/coredns/adblock'))
    parser.add_argument('--refresh', action='store_true', help='download sources before rebuilding')
    args = parser.parse_args()
    with (args.directory / '.update.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        result = update(json.loads(args.config.read_text()), args.directory, args.refresh)
    print(json.dumps(result))


if __name__ == '__main__':
    main()
